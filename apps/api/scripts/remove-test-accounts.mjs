#!/usr/bin/env node
/**
 * Removes the test accounts created while building and verifying the platform.
 *
 * Dry run by default — it prints exactly what it would delete and changes nothing. Pass
 * --execute to actually do it.
 *
 * Run it where DATABASE_URL points at the database you mean:
 *   railway ssh --service api -- node scripts/remove-test-accounts.mjs
 *   railway ssh --service api -- node scripts/remove-test-accounts.mjs --execute
 *
 * Three deliberate safety properties:
 *
 *   The list is explicit prefixes, not a sweep of @example.com. A real person could sign up
 *   with an example.com address, and this is not reversible.
 *
 *   Anything that owns a cohort is skipped. Cohorts cannot be deleted — only archived — so
 *   removing an owner would fail on a foreign key anyway, and silently leaving a cohort
 *   ownerless would be worse than leaving the account.
 *
 *   Each account is handled on its own. One failure reports and moves on rather than
 *   abandoning the rest half-done.
 */
import { PrismaClient } from '@prisma/client';

// Every prefix here was generated by a test run. claude-instructor-* and delivered@resend.dev
// are deliberately absent: the first owns cohorts, the second is a verified fixture worth
// keeping for future checks.
const TEST_PREFIXES = [
  'e2e-',
  'verifyrepro-',
  'verifyfix-',
  'repro-',
  'post-deploy-',
  'final-',
  'wrap-',
  'recovery-',
  'invitee-',
  'newtutor-',
  'realtutor-',
  'guardtest-',
  'browser-recovery-',
  'postrestart-',
  'verify-round',
  'mvp-check-',
  'dashboard-verify-',
  'verify-final-',
  'verify-org',
  'verify-mfa-',
  'stranger-',
  'claude-emailcheck-',
];

const execute = process.argv.includes('--execute');
const prisma = new PrismaClient();

async function main() {
  const where = { OR: TEST_PREFIXES.map((p) => ({ email: { startsWith: p } })) };
  const users = await prisma.user.findMany({
    where,
    select: { id: true, email: true },
    orderBy: { createdAt: 'asc' },
  });

  if (users.length === 0) {
    console.log('Nothing to remove.');
    return;
  }

  const removable = [];
  const skipped = [];
  for (const user of users) {
    const owned = await prisma.cohort.count({ where: { ownerId: user.id } });
    if (owned > 0) {
      skipped.push(`${user.email} — owns ${owned} cohort(s)`);
    } else {
      removable.push(user);
    }
  }

  console.log(`${removable.length} account(s) to remove:`);
  for (const u of removable) console.log(`   ${u.email}`);
  if (skipped.length) {
    console.log(`\n${skipped.length} skipped:`);
    for (const s of skipped) console.log(`   ${s}`);
  }

  const total = await prisma.user.count();
  console.log(`\n${total} users before; ${total - removable.length} after.`);

  if (!execute) {
    console.log('\nDry run — nothing was changed. Re-run with --execute to apply.');
    return;
  }

  let removed = 0;
  const failed = [];
  for (const user of removable) {
    try {
      // These reference the user without cascading, so they block the delete if left.
      await prisma.cohortEnrollment.deleteMany({ where: { userId: user.id } });
      await prisma.cohortStaff.deleteMany({ where: { userId: user.id } });
      await prisma.investigationSession.deleteMany({ where: { userId: user.id } });
      await prisma.user.delete({ where: { id: user.id } });
      removed += 1;
    } catch (err) {
      failed.push(`${user.email} — ${String(err.message).split('\n')[0].slice(0, 100)}`);
    }
  }

  console.log(`\nRemoved ${removed} of ${removable.length}.`);
  if (failed.length) {
    console.log('Failed:');
    for (const f of failed) console.log(`   ${f}`);
  }
  console.log(`Users now: ${await prisma.user.count()}`);
}

main()
  .catch((err) => {
    console.error(err);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
